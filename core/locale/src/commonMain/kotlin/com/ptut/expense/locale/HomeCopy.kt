    val checkedAgo: (since: String) -> String = { since -> "checked $since ago" },
    val noFolderWatched: String = "No folder watched · pick one in Settings",
    val watchingOne: (folder: String, checked: String) -> String = { folder, checked -> "Watching $folder · $checked" },
    val watchingMany: (count: Int, checked: String) -> String = { count, checked -> "Watching $count folders · $checked" },
    val slipsToCheck: (Int) -> String = { n -> if (n == 1) "1 slip to check" else "$n slips to check" },
    val newShops: (Int) -> String = { n -> "${n.homeSpelled()} new shop${n.homePlural()}" },
    val unreadableAmounts: (Int) -> String = { n -> "${n.homeSpelled()} unreadable amount${n.homePlural()}" },
    val unreadSlips: (Int) -> String = { n -> "${n.homeSpelled()} unread slip${n.homePlural()}" },
    val reasonSeparator: String = ", ",
    val goodMorning: String = "Good morning",
    val yesterdayCameTo: (spent: String, versus: String) -> String = { spent, versus -> "Yesterday came to $spent$versus." },
    val dayWrapped: String = "Your day, wrapped",
    val wrapLine: (count: Int, total: String) -> String = { count, total ->
        "${count.homeCounted()} ${if (count == 1) "purchase" else "purchases"}, $total. Tap for the receipt."
    },
)

private fun Int.homeSpelled(): String = if (this == 1) "one" else toString()

private fun Int.homePlural(): String = if (this == 1) "" else "s"

private fun Int.homeCounted(): String = HOME_COUNT_WORDS.getOrNull(this) ?: toString()

private val HOME_COUNT_WORDS = listOf("No", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine", "Ten")

