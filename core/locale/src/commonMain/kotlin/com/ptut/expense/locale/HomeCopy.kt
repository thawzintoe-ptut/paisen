    val notNow: String = "Not now",
    val totalsIncomplete: String = "Totals below may be incomplete",
    val fix: String = "Fix",
    val net: String = "Net",
    val quietDay: String = "A quiet day so far.",
    val quietWeek: String = "A quiet week so far.",
