package com.ptut.expense.locale

/**
 * Words for money in another currency: a kyat slip that asks for a rate (#33), and the Add sheet's
 * currency and rate. Its own file, read through [currencyCopy], so it needs no field on [Copy]. A
 * language with no entry here reads the English. [unit] is "1,000 K" or "$", what one rate buys.
 */
data class CurrencyCopy(
    val rateNeeded: (code: String) -> String = { code -> "A $code slip needs a rate" },
    val rateNeededBody: (shop: String, amount: String) -> String = { shop, amount -> "$shop · $amount · add the rate in To check" },
    val reasonRate: String = "Rate needed",
    val rateLabel: String = "Rate",
    val perUnit: (home: String, unit: String) -> String = { home, unit -> "$home per $unit" },
    val todaysRate: String = "See today's rate",
    val askRate: String = "Type the rate first",
    val inBaht: (baht: String) -> String = { baht -> "Saved as $baht" },
    val rateNote: String = "Later entries in this currency use this rate until you change it.",
    val paidLabel: String = "Paid",
    val slipsNeedRate: (Int) -> String = { n -> if (n == 1) "one needs a rate" else "$n need a rate" },
    val atRate: (amount: String, home: String, rate: String, unit: String) -> String = { amount, home, rate, unit -> "$amount at $home$rate per $unit" },
    val currencyTitle: String = "Currency",
    val startsIn: String = "Add starts in",
    val startsInIntro: String = "The Add sheet opens on this currency. Totals still count in baht.",
    val fromPhone: (code: String) -> String = { code -> "$code · from this phone" },
    val followPhone: (code: String) -> String = { code -> "Follow this phone ($code)" },
    val rateFor: (code: String) -> String = { code -> "Rate for $code" },
    val setRate: (code: String) -> String = { code -> "Set the rate for $code" },
    val converted: (amount: String, home: String, rate: String, unit: String) -> String = { amount, home, rate, unit -> "$amount · $home$rate per $unit" },
    val rateOnly: (home: String, rate: String, unit: String) -> String = { home, rate, unit -> "$home$rate per $unit" },
    /** A screen reader's amount in a currency other than baht: "29,500 MMK". */
    val spoken: (digits: String, code: String) -> String = { digits, code -> "$digits $code" },
    val yourMoney: String = "Your money",
    val homeValue: (code: String, symbol: String) -> String = { code, symbol -> "$code ($symbol)" },
    val change: String = "Change",
    val homeTitle: String = "Home currency",
    val homeRowValue: (code: String, zone: String) -> String = { code, zone -> "$code · $zone" },
    val homeIntro: (zone: String) -> String = { zone -> "Every total counts in this currency. Days start at midnight, $zone time." },
    val homeHasRows: String = "Your ledger already has entries, so changing this converts every amount.",
    val convertTitle: (code: String) -> String = { code -> "Change to $code?" },
    val convertBody: String = "Every amount converts at this rate. Each entry keeps its old amount and the rate beside it.",
    val convertExample: (from: String, to: String) -> String = { from, to -> "$from becomes $to" },
    val backupFirst: String = "Export a backup first",
    val convertAction: String = "Change",
    val convertFailed: String = "Nothing changed. The entries could not be converted.",
)

