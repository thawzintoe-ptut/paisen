/** Who pays whom: the payments that settle one group. */
data class SharedSettleCopy(
    val toSettle: (String) -> String = { group -> "To settle $group" },
    val between: (Int) -> String = { n -> "$n between everyone" },
    val then: String = "then",
    val afterSimplifying: (Int) -> String = { n -> "$n after simplifying" },
    val simplify: String = "Simplify debts",
    val settleAPayment: String = "Settle a payment",
    val paysYou: (String) -> String = { from -> "$from pays you" },
    val youPay: (String) -> String = { to -> "You pay $to" },
    val pays: (String, String) -> String = { from, to -> "$from pays $to" },
    val allSettled: String = "All settled",
    val payments: (Int) -> String = { n -> if (n == 1) "1 payment" else "$n payments" },
    val converted: (List<String>) -> String = { codes ->
        "Amounts in ${codes.joinToString(" and ")} were converted to THB at the rate saved on each expense, so nobody's total moves with the market."
    },
)

