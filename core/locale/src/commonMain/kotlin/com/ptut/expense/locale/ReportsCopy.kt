package com.ptut.expense.locale

/** Reports: the period tabs, the total, the chart and the categories under it. */
data class ReportsCopy(
    val title: String = "Spending",
    val spent: (range: String) -> String = { range -> "Spent $range" },
    val threeMonths: String = "3 months",
    val sixMonths: String = "6 months",
    val twelveMonths: String = "12 months",
    val weekOf: (date: String) -> String = { date -> "Week of $date" },
    val average: (amount: String) -> String = { amount -> "avg $amount" },
    val purchases: (Int) -> String = { n -> if (n == 1) "1 purchase" else "$n purchases" },
    val lastWeek: String = "last week",
    val lastMonth: String = "last month",
    val threeMonthsBefore: String = "the 3 months before",
    val sixMonthsBefore: String = "the 6 months before",
    val yearBefore: String = "the year before",
    val same: String = "same",
    val tabWeek: String = "W",
    val tabMonth: String = "M",
    val tabThreeMonths: String = "3M",
    val tabSixMonths: String = "6M",
    val tabYear: String = "Y",
    val spokenWeek: String = "Week",
    val spokenMonth: String = "Month",
    val spokenYear: String = "Year",
    val net: String = "Net",
    val topCategories: String = "Top categories",
    val nothingSpent: String = "Nothing was spent in this period.",
    val nothingToChart: String = "Nothing to chart yet.",
    val emptyBody: (bucket: String) -> String =
        { bucket -> "Bars fill in as purchases arrive. A $bucket with no spend shows a short stub, never a gap." },
    val bucketDay: String = "day",
    val bucketWeek: String = "week",
    val bucketMonth: String = "month",
    val buildsItself: String = "Reports build themselves as slips arrive",
    val weekAxis: List<String> = listOf("M", "T", "W", "T", "F", "S", "S"),
    val yearAxis: List<String> = listOf("J", "F", "M", "A", "M", "J", "J", "A", "S", "O", "N", "D"),
    val showInHistory: String = "Show in History",
)

