internal const val SHARED_MY_YOU = "သင်"

internal fun sharedEnYou(name: String): String = if (name == "You") "you" else name

internal fun sharedMyBy(name: String): String = if (name == SHARED_MY_YOU) name else "$name က"

internal fun sharedMyTo(name: String): String = if (name == SHARED_MY_YOU) "သင့်ကို" else "$name ကို"

internal fun sharedMyWith(name: String): String = if (name == SHARED_MY_YOU) "သင်နဲ့" else "$name နဲ့"
